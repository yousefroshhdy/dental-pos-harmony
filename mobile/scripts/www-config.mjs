// Runs before `cap copy` / `cap sync` (the "capacitor:copy:before" hook in package.json):
// writes www/config.js so the offline fallback page knows where "Try again" goes.
// Same rule as capacitor.config.ts: CAP_SERVER_URL, https only, default = staging.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SERVER_URL = "https://honest-os-staging.vercel.app";
const url = new URL((process.env.CAP_SERVER_URL ?? "").trim() || DEFAULT_SERVER_URL);
if (url.protocol !== "https:") throw new Error(`CAP_SERVER_URL must be https (got ${url.protocol})`);

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "www", "config.js");
writeFileSync(out, `// Generated by scripts/www-config.mjs at cap sync; do not edit.\nwindow.HONEST_SERVER_URL = ${JSON.stringify(url.origin + "/")};\n`);
console.log(`www/config.js → ${url.origin}/`);
