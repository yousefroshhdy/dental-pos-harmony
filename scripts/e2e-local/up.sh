#!/usr/bin/env bash
# Local signed-in stack for screenshots and manual checks (docs/TESTING.md "Local signed-in stack").
# LOCAL TEST HARNESS ONLY: synthetic data, mock auth, never deploy any of it.
#
#   pnpm e2e:local:up            # setup + start (idempotent: a running stack is left alone)
#   pnpm e2e:local:up --keep-db  # reuse the existing honest_e2e_local database
#   pnpm e2e:local:down          # stop everything (and forget the per-run secret)
#
# What runs (all on 127.0.0.1):
#   PostgreSQL 16   $PGHOST:$PGPORT (default /var/tmp/honestpg:54329), database honest_e2e_local
#   PostgREST       :54322  (pinned static binary, SHA-256 checked, cached in .cache/e2e-local/)
#   gateway + auth  :54321  (scripts/e2e-local/mock-auth.mjs: /rest/v1 → PostgREST, /auth/v1 mock)
#   app             :3210   (`pnpm build` + `pnpm start` with the local env; no Google keys)
#
# The JWT secret, keys and the shared demo password are generated into the git-ignored
# .cache/e2e-local/env.local at run time (down.sh deletes it, so each run gets a new secret).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
CACHE="${ROOT}/.cache/e2e-local"
ENV_FILE="${CACHE}/env.local"
PIDS="${CACHE}/pids"
LOGS="${CACHE}/logs"
mkdir -p "${CACHE}" "${PIDS}" "${LOGS}"

export PGHOST="${PGHOST:-/var/tmp/honestpg}" PGPORT="${PGPORT:-54329}" PGUSER="${PGUSER:-postgres}"
export PGOPTIONS="${PGOPTIONS:-} -c client_min_messages=warning"
export NEXT_TELEMETRY_DISABLED=1
DB="${E2E_LOCAL_DB:-honest_e2e_local}"
GATEWAY_PORT="${E2E_GATEWAY_PORT:-54321}"
POSTGREST_PORT="${E2E_POSTGREST_PORT:-54322}"
APP_PORT="${E2E_LOCAL_APP_PORT:-3210}"
PSQL=(psql -X -q -v ON_ERROR_STOP=1 --no-psqlrc)

POSTGREST_VERSION="v12.2.3"
POSTGREST_URL="https://github.com/PostgREST/postgrest/releases/download/${POSTGREST_VERSION}/postgrest-${POSTGREST_VERSION}-linux-static-x64.tar.xz"
POSTGREST_SHA256="9f71269e61ac3a940281e93ff415760f5957e430e475ba4c3889f3ede7d5527c"

KEEP_DB=0
for arg in "$@"; do
  case "$arg" in
    --keep-db) KEEP_DB=1 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

alive() { [[ -f "${PIDS}/$1.pid" ]] && kill -0 "$(cat "${PIDS}/$1.pid")" 2>/dev/null; }

if alive postgrest && alive gateway && alive app; then
  echo "local stack already up: app http://127.0.0.1:${APP_PORT} (pnpm e2e:local:down to stop)"
  exit 0
fi
# Partly up: stop the leftovers but keep the secret, so --keep-db stays consistent.
E2E_LOCAL_KEEP_ENV=1 bash "${ROOT}/scripts/e2e-local/down.sh" >/dev/null 2>&1 || true

# ---------------------------------------------------------------------------- PostgreSQL
if ! pg_isready -q -h "${PGHOST}" -p "${PGPORT}"; then
  echo "== starting PostgreSQL 16 on ${PGHOST}:${PGPORT}"
  rm -f /var/tmp/honestpg/data/postmaster.pid
  su postgres -c "/usr/lib/postgresql/16/bin/pg_ctl -D /var/tmp/honestpg/data -o '-p ${PGPORT} -k ${PGHOST}' -l /var/tmp/honestpg/log start" >/dev/null
  for _ in $(seq 1 30); do pg_isready -q -h "${PGHOST}" -p "${PGPORT}" && break; sleep 1; done
fi

# ---------------------------------------------------------------------------- PostgREST binary
if [[ ! -x "${CACHE}/postgrest" && ! -f "${CACHE}/postgrest.tar.xz" ]]; then
  echo "== downloading PostgREST ${POSTGREST_VERSION}"
  curl -fsSL --max-time 300 -o "${CACHE}/postgrest.tar.xz" "${POSTGREST_URL}"
fi
if [[ -f "${CACHE}/postgrest.tar.xz" ]]; then
  echo "${POSTGREST_SHA256}  ${CACHE}/postgrest.tar.xz" | sha256sum -c --quiet - \
    || { echo "PostgREST archive checksum mismatch; delete ${CACHE}/postgrest.tar.xz and retry" >&2; exit 1; }
  [[ -x "${CACHE}/postgrest" ]] || tar -xJf "${CACHE}/postgrest.tar.xz" -C "${CACHE}"
fi

# ---------------------------------------------------------------------------- per-run secrets
if [[ ! -f "${ENV_FILE}" ]]; then
  secret="$(openssl rand -hex 32)"
  keys="$(node "${ROOT}/scripts/e2e-local/jwt.mjs" keys "${secret}")"
  anon="$(sed -n 's/^ANON_KEY=//p' <<<"${keys}")"
  service="$(sed -n 's/^SERVICE_ROLE_KEY=//p' <<<"${keys}")"
  umask 077
  cat >"${ENV_FILE}" <<EOF
# Generated by scripts/e2e-local/up.sh for the LOCAL stack only. Git-ignored; deleted by down.sh.
E2E_JWT_SECRET=${secret}
E2E_LOCAL_PASSWORD=demo-$(openssl rand -hex 6)
E2E_AUTHENTICATOR_PASSWORD=$(openssl rand -hex 16)
NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:${GATEWAY_PORT}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}
NEXT_PUBLIC_APP_URL=http://127.0.0.1:${APP_PORT}
NEXT_PUBLIC_GOOGLE_MAPS_API_KEY=
SUPABASE_SERVICE_ROLE_KEY=${service}
CRON_SECRET=$(openssl rand -hex 32)
OUTBOX_SIGNING_SECRET=$(openssl rand -hex 32)
GOOGLE_MAPS_SERVER_KEY=
E2E_LOCAL_APP_PORT=${APP_PORT}
EOF
  umask 022
fi
set -a; source "${ENV_FILE}"; set +a

# ---------------------------------------------------------------------------- database
db_exists() { [[ "$("${PSQL[@]}" -d postgres -Atc "select 1 from pg_database where datname = '${DB}'")" == "1" ]]; }
if [[ ${KEEP_DB} -eq 0 ]] || ! db_exists; then
  echo "== building database ${DB} (stub, shim, migrations, seed, fixture, demo data)"
  "${PSQL[@]}" -d postgres -c "drop database if exists ${DB} with (force)" -c "create database ${DB}" >/dev/null
  "${PSQL[@]}" -d "${DB}" -c "alter database ${DB} set search_path = \"\$user\", public, extensions" >/dev/null
  "${PSQL[@]}" -d "${DB}" -f "${ROOT}/scripts/db/local_supabase_stub.sql" >/dev/null
  "${PSQL[@]}" -d "${DB}" -f "${ROOT}/scripts/db/local_pgtap_shim.sql" >/dev/null
  for f in "${ROOT}"/supabase/migrations/*.sql; do "${PSQL[@]}" -d "${DB}" -f "$f" >/dev/null; done
  "${PSQL[@]}" -d "${DB}" -f "${ROOT}/supabase/seed.sql" >/dev/null
  "${PSQL[@]}" -d "${DB}" -c "select tests.load_fixture()" >/dev/null
  "${PSQL[@]}" -d "${DB}" -f "${ROOT}/scripts/e2e-local/demo-seed.sql" >/dev/null
fi
# PostgREST's login role (cluster-wide, local only), like Supabase's `authenticator`.
"${PSQL[@]}" -d "${DB}" >/dev/null <<SQL
do \$\$ begin
  if not exists (select 1 from pg_roles where rolname = 'authenticator') then
    create role authenticator login noinherit;
  end if;
end \$\$;
alter role authenticator with login noinherit password '${E2E_AUTHENTICATOR_PASSWORD}';
grant anon, authenticated, service_role to authenticator;
SQL
"${PSQL[@]}" -d "${DB}" -At -c "select coalesce(json_agg(json_build_object('id', id, 'email', email,
    'aal', case when email = 'owner@honest.test' then 'aal2' else 'aal1' end) order by email), '[]')
  from auth.users" >"${CACHE}/users.json"

# ---------------------------------------------------------------------------- PostgREST + gateway
cat >"${CACHE}/postgrest.conf" <<EOF
db-uri = "postgres://authenticator:${E2E_AUTHENTICATOR_PASSWORD}@/${DB}?host=${PGHOST}&port=${PGPORT}"
db-schemas = "api,service"
db-anon-role = "anon"
db-extra-search-path = "extensions"
db-max-rows = 1000
jwt-secret = "${E2E_JWT_SECRET}"
server-host = "127.0.0.1"
server-port = ${POSTGREST_PORT}
log-level = "warn"
EOF
chmod 600 "${CACHE}/postgrest.conf"

start() { # name, command...
  local name="$1"; shift
  # Own process group (setsid), so down.sh stops the whole tree (pnpm → next-server).
  setsid nohup "$@" >"${LOGS}/${name}.log" 2>&1 < /dev/null &
  echo $! >"${PIDS}/${name}.pid"
}
wait_for() { # url, name
  for _ in $(seq 1 120); do curl -fsS -o /dev/null "$1" 2>/dev/null && return 0; sleep 1; done
  echo "$2 did not come up; see ${LOGS}/$2.log" >&2; tail -20 "${LOGS}/$2.log" >&2; exit 1
}

echo "== starting PostgREST :${POSTGREST_PORT} and gateway :${GATEWAY_PORT}"
start postgrest "${CACHE}/postgrest" "${CACHE}/postgrest.conf"
E2E_GATEWAY_PORT="${GATEWAY_PORT}" E2E_POSTGREST_PORT="${POSTGREST_PORT}" E2E_USERS_FILE="${CACHE}/users.json" \
  start gateway node "${ROOT}/scripts/e2e-local/mock-auth.mjs"
wait_for "http://127.0.0.1:${POSTGREST_PORT}/" postgrest
wait_for "http://127.0.0.1:${GATEWAY_PORT}/auth/v1/health" gateway

# ---------------------------------------------------------------------------- app
# NEXT_PUBLIC_* are inlined at build time, so the build uses this run's anon key and URLs.
# The exported (empty) Google keys override any developer .env.local: maps stay "not configured".
cd "${ROOT}"
echo "== building the app (pnpm build; log in ${LOGS}/build.log)"
pnpm build >"${LOGS}/build.log" 2>&1 || { tail -40 "${LOGS}/build.log" >&2; exit 1; }
echo "== starting the app :${APP_PORT}"
start app pnpm start --hostname 127.0.0.1 --port "${APP_PORT}"
wait_for "http://127.0.0.1:${APP_PORT}/api/health" app

cat <<EOF

local stack up (synthetic data only):
  app       http://127.0.0.1:${APP_PORT}
  gateway   http://127.0.0.1:${GATEWAY_PORT}  (/rest/v1 → PostgREST :${POSTGREST_PORT}, /auth/v1 → mock auth)
  database  ${DB} on ${PGHOST}:${PGPORT}
  sign in   owner@honest.test (aal2), sd@, am.cairo@, rep.cairo@, rep.delta@, finance@, admin@, inventory@honest.test
  password  E2E_LOCAL_PASSWORD in ${ENV_FILE}
  shots     pnpm e2e:local:shots   ·   stop: pnpm e2e:local:down
EOF
