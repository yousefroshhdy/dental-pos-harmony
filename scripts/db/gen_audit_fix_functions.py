"""One-off generator for supabase/migrations/20261029001050_audit_fix_functions.sql.

Copies each function verbatim from the migration that defines it (already
tested) and applies minimal, asserted text replacements for the audit fixes.
Kept in the repo so reviewers can see exactly what changed vs. the original.
Run: python3 -I scripts/db/gen_audit_fix_functions.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
MIG = ROOT / "supabase" / "migrations"


def extract(filename: str, signature: str) -> str:
    text = (MIG / filename).read_text()
    start = text.index(f"create or replace function {signature}")
    end = text.index("end $$;", start) + len("end $$;")
    return text[start:end]


def patch(body: str, old: str, new: str) -> str:
    assert body.count(old) == 1, f"expected exactly one match for: {old[:70]!r}"
    return body.replace(old, new)


